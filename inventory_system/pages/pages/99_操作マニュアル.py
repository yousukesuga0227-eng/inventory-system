import streamlit as st
from auth import check_login

check_login()

st.set_page_config(
    page_title="操作マニュアル",
    page_icon="📖",
    layout="wide"
)

st.title("📖 SHARK 操作マニュアル")
st.caption("SHARK 在庫管理システム Ver1.0")

st.info("分からない操作があれば、該当する項目を開いて確認してください。")

with st.expander("🦈 システムの流れ", expanded=True):
    st.markdown("""
    1. 案件登録  
    2. 商品登録  
    3. 入庫登録  
    4. 出庫登録  
    5. 在庫確認  
    6. 棚卸・出荷前チェック  
    """)

with st.expander("① 案件登録"):
    st.markdown("""
    新しい案件が決まった場合は、**案件管理**を開きます。

    入力する内容：

    - 案件コード
    - 案件名
    - 入庫予定日
    - 出荷予定日
    - 備考

    入力後、**登録**を押してください。

    ※案件は商品登録で使用します。
    """)

with st.expander("② 商品登録"):
    st.markdown("""
    案件登録後、**商品管理**を開きます。

    入力する内容：

    - 案件
    - 商品コード
    - 商品名
    - 必要数量

    入力後、**登録**を押してください。

    ※同じ商品を重複登録しないよう注意してください。
    """)

with st.expander("③ 入庫登録"):
    st.markdown("""
    商品が入荷したら、**入出庫登録**を開きます。

    1. 案件を選択
    2. 商品を選択、またはバーコードを読み取る
    3. 数量を入力
    4. **入庫**を押す

    これで入庫登録完了です。
    """)

with st.expander("④ 出庫登録"):
    st.markdown("""
    商品を出荷したら、**入出庫登録**を開きます。

    1. 案件を選択
    2. 商品を選択、またはバーコードを読み取る
    3. 数量を入力
    4. **出庫**を押す

    これで出庫登録完了です。
    """)

with st.expander("⑤ 在庫一覧"):
    st.markdown("""
    **在庫一覧**では以下を確認できます。

    - 案件名
    - 商品コード
    - 商品名
    - 現在庫数

    検索機能を使うと、目的の商品を探しやすくなります。
    """)

with st.expander("⑥ 棚卸"):
    st.markdown("""
    棚卸を行う場合は、**棚卸**を開きます。

    1. 商品を検索
    2. 実際の数量を入力
    3. 保存

    これで棚卸データが登録されます。
    """)

with st.expander("⑦ 出荷前チェック"):
    st.markdown("""
    出荷前は以下を必ず確認してください。

    - 案件が正しいか
    - 商品が正しいか
    - 数量が正しいか

    バーコードチェック機能がある場合は、読み取り確認後に出荷してください。
    """)

with st.expander("❓ よくある質問"):
    st.markdown("""
    **Q. 数量を間違えて登録しました。**  
    A. 管理者へ連絡してください。

    **Q. 商品が見つかりません。**  
    A. 商品登録されているか、案件が正しいか確認してください。

    **Q. 在庫が合いません。**  
    A. 入出庫履歴・棚卸結果を確認してください。
    """)

st.warning("""
注意事項

- 実物を確認して登録してください。
- 同じ商品を二重登録しないでください。
- 不明な場合は担当者へ確認してください。
""")

st.success("🦈 SHARKルール：迷ったら登録。分からなければ確認。")