with st.expander("🦈 まずここ：SHARKの基本ルール", expanded=True):
    st.markdown(
        """
### 案件在庫の基本フロー
1. **案件・商品追加**で案件と商品を登録
2. **ラベル出力**で必要なラベル／A4商品票を作成
3. **入出庫 → 入庫**で入荷商品を登録
4. 出荷時は**出荷指示書**を見てピッキング
5. 積込前に**QR／バーコードを読み取る**
6. 内容を確認して**出庫確定**
7. **納品書・受領書**を保存

### パレット在庫の基本フロー
1. **パレット在庫 → 登録・印刷**で必要事項を登録
2. **1パレットにつきA4を1枚**印刷
3. **QR入出庫 → 入庫**でA4のQRを1枚ずつ読む
4. 出庫時は**QR入出庫 → 出庫**で対象パレットを追加
5. 内容を確認して**出庫確定**
6. **納品書・受領書**を保存

**大事なルール**
- 実物・案件・商品・数量を確認してから確定する
- QRを読んだだけでは出庫確定にならない画面があります
- エラーが出た状態で無理に別商品として登録しない
- 数量や案件を間違えた場合は、自己判断で履歴を消さず管理者へ確認する
        """
    )

