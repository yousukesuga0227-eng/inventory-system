with st.expander("❓ よくあるエラー・困ったとき"):
    st.markdown(
        """
### Q. 「バーコードに一致する商品がありません」
**A.** 選択中の案件に商品が登録されているか、QR／商品コードが正しいか確認してください。

### Q. 出庫で「案件違い」と出る
**A.** 選択中の案件と、読んだ商品の所属案件を確認してください。  
正しい案件を選び直してから再度読み取ります。

### Q. 同じA4 QRを2回読んでしまった
**A.** 案件商品の出庫では個別QRの二重読取を検知し、数量を増やさないようになっています。

### Q. QRを読んだのに在庫が減っていない
**A.** 出庫画面では読取後に**出庫確定**が必要です。  
「今回の出庫」の内容を確認して確定してください。

### Q. 在庫が合わない
**A.** まず**入出庫履歴**を確認し、必要なら管理者が**棚卸**で実棚との差異を登録します。

### Q. 数量を間違えて登録した
**A.** 履歴削除は在庫数に影響します。管理者へ確認してください。

### Q. 商品や案件が選択肢に出ない
**A.** 商品・案件が非表示になっている可能性があります。管理者の**案件・商品編集 → 非表示管理**を確認してください。

### Q. パレット出庫で別荷主を追加できない
**A.** 1回の出庫・1組の納品書／受領書に別荷主は混在できません。荷主ごとに分けて出庫してください。
        """
    )

