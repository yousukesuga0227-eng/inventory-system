with st.expander("② 🏷️ ラベル・A4商品票を出す"):
    st.markdown(
        """
**ラベル出力**を開き、最初に案件を選択します。

### ラベルプリント
1. **印刷形式 → ラベルプリント**
2. 対象商品を選択
3. 印刷枚数を選択
   - **任意枚数印刷**
   - **出荷数分印刷**
4. 必要なら個体連番の開始番号を指定
5. 出力方法を選ぶ
   - **📄 ラベルPDFをダウンロード**
   - **🖼️ ラベルPNGをZIPでダウンロード**
   - **🖨️ QL-820へ直接印刷**
   - **🦈 倉庫プリンターへ遠隔印刷**

通常ラベルのバーコードには個体連番が付きます。

### A4プリント
1. **印刷形式 → A4プリント**
2. 対象商品を選択
3. **「📄 A4出荷商品票をまとめてダウンロード」**
4. PDFを**A4・横向き**で印刷

A4商品票は**1商品につき1ページ**です。  
数量別A4のQRは個体通番付きで、例：`商品コード|1/2` のような形式になります。
SHARKはこのQRを読んだとき、元の商品コードを自動判定します。
        """
    )

