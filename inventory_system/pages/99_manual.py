with st.expander("④ 📤 案件商品の出庫【重要】", expanded=True):
    st.markdown(
        """
現在の正式な出庫フローは、**手入力で数量を引く方式ではありません。**

### 1. 案件を選ぶ
**入出庫 → 📤 出庫**を開き、出荷する案件を選択します。

### 2. 出荷指示書を出す
**「📄 出荷指示書をダウンロード」**を押し、指示書を見ながらピッキングします。

### 3. 積込前にQR／バーコードを読む
実際に積み込む商品だけを順番に読み取ります。

- 読み取った商品と数量が「今回の出庫」に追加されます
- A4個別QRは同じQRを二重読取しても数量を増やしません
- 選択中の案件に無い商品は**「案件違い」**として止まります
- 間違えた場合は、確定前に読取内容を戻す／リセットします

### 4. 出庫確定
読取内容を確認し、  
**「✅ 読み取った ○個を出庫確定」**を押します。

在庫不足や案件残数を超えている場合は確定できません。

### 5. 帳票を保存
出庫完了後に表示される

- **📄 納品書**
- **📄 受領書**

を保存してください。

次の出庫に移るときは**「🧹 次の出庫を開始」**を押します。

**注意：QRを読んだだけでは出庫完了ではありません。必ず最後に「出庫確定」まで行ってください。**
        """
    )

